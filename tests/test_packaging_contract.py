# ---------------------------------------------------------------------------
# Functional pruning check on a synthetic runtime copy (no 624 MB asset needed).
# The real fixed runtime is never touched: only a temporary miniature runtime.
# ---------------------------------------------------------------------------
def _build_synthetic_runtime(root: Path, policy: dict) -> None:
    keep = policy["keep"]
    prune = policy["prune"]

    for relative in list(keep["requiredFiles"]) + list(keep["requiredNestedFiles"]):
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"required-stub" * 16)

    for relative in keep["requiredDirectories"]:
        (root / relative).mkdir(parents=True, exist_ok=True)

    locales_dir = root / "Locales"
    locales_dir.mkdir(parents=True, exist_ok=True)
    for locale_name in list(keep["localeFiles"]) + ["de-DE.pak", "fr-FR.pak"]:
        (locales_dir / locale_name).write_bytes(b"locale-stub" * 16)

    for relative in list(prune["topLevelEntries"]) + list(prune["nestedPaths"]):
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if Path(relative).suffix:
            path.write_bytes(b"prunable-stub" * 64)
        else:
            path.mkdir(exist_ok=True)
            (path / "payload.bin").write_bytes(b"prunable-stub" * 64)

    # Entries that are not in the policy must always survive pruning.
    (root / "UnknownFutureDir").mkdir()
    (root / "UnknownFutureDir" / "data.bin").write_bytes(b"keep-me")
    (root / "unknown-future.dll").write_bytes(b"keep-me")


def _run_pruner(runtime_dir: Path, report_path: Path, *extra_arguments: str) -> subprocess.CompletedProcess:
    if os.name != "nt":
        pytest.skip("Windows PowerShell is required to exercise the WebView2 pruner")
    powershell = shutil.which("powershell")
    if powershell is None:
        pytest.skip("Windows PowerShell is not available in this environment")

    command = [
        powershell,
        "-NoProfile",
        "-NonInteractive",
        "-ExecutionPolicy",
        "Bypass",
        "-File",
        str(PRUNE_SCRIPT_PATH),
        "-RuntimeDir",
        str(runtime_dir),
        "-PolicyPath",
        str(PRUNE_POLICY_PATH),
        "-ReportPath",
        str(report_path),
    ]
    command.extend(extra_arguments)
    return subprocess.run(
        command,
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=180,
    )


def test_webview2_pruner_dry_run_is_non_destructive_and_idempotent(tmp_path):
    policy = _load_prune_policy()
    runtime_dir = tmp_path / "webview2-fixed"
    runtime_dir.mkdir()
    _build_synthetic_runtime(runtime_dir, policy)

    dry_run_report = tmp_path / "dry-run.json"
    dry_run = _run_pruner(runtime_dir, dry_run_report, "-DryRun")
    assert dry_run.returncode == 0, dry_run.stderr
    dry_payload = json.loads(dry_run_report.read_text(encoding="utf-8"))
    assert dry_payload["dryRun"] is True
    assert dry_payload["candidateCount"] > 0
    assert dry_payload["candidateBytes"] > 0
    assert dry_payload["removedCount"] == 0
    assert (runtime_dir / "WidevineCdm").exists(), "dry-run must not delete files"
    assert (runtime_dir / "Locales" / "de-DE.pak").exists(), "dry-run must not delete locale files"

    first_report = tmp_path / "run-1.json"
    first = _run_pruner(runtime_dir, first_report)
    assert first.returncode == 0, first.stderr
    payload = json.loads(first_report.read_text(encoding="utf-8"))
    assert payload["removedCount"] == payload["candidateCount"] > 0
    assert payload["requiredEntriesVerified"] is True
    for relative in list(policy["keep"]["requiredFiles"]) + list(policy["keep"]["requiredNestedFiles"]):
        assert (runtime_dir / relative).is_file(), f"pruning removed required entry: {relative}"
    kept_locales = sorted(path.name for path in (runtime_dir / "Locales").iterdir())
    assert kept_locales == sorted(policy["keep"]["localeFiles"])
    assert not (runtime_dir / "WidevineCdm").exists()
    assert not (runtime_dir / "EBWebView" / "x86").exists()
    assert (runtime_dir / "UnknownFutureDir" / "data.bin").is_file(), "unknown entries must be kept"
    assert (runtime_dir / "unknown-future.dll").is_file(), "unknown entries must be kept"

    second_report = tmp_path / "run-2.json"
    second = _run_pruner(runtime_dir, second_report)
    assert second.returncode == 0, second.stderr
    second_payload = json.loads(second_report.read_text(encoding="utf-8"))
    assert second_payload["candidateCount"] == 0
    assert second_payload["removedCount"] == 0
    assert "already pruned" in second.stdout


def test_webview2_pruner_refuses_partial_runtime(tmp_path):
    runtime_dir = tmp_path / "partial-webview2"
    runtime_dir.mkdir()
    (runtime_dir / "Locales").mkdir()
    (runtime_dir / "Locales" / "en-US.pak").write_bytes(b"stub")
    (runtime_dir / "msedgewebview2.exe").write_bytes(b"stub")

    report_path = tmp_path / "partial.json"
    result = _run_pruner(runtime_dir, report_path)
    assert result.returncode != 0, "pruner must fail when startup-critical entries are missing"
    combined_output = f"{result.stdout}\n{result.stderr}"
    assert "startup-critical" in combined_output
    assert (runtime_dir / "msedgewebview2.exe").exists(), "failed prune must not delete anything"
    assert not report_path.exists(), "failed prune must not write a success report"
