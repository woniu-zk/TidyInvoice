def test_resources_manifest_required_paths_and_datas_resolve():
    manifest = _load_manifest()
    assert manifest["requiredPaths"]
    assert manifest["datas"]

    for relative in manifest["requiredPaths"]:
        normalized = str(relative).replace("\\", "/")
        if normalized.startswith("build/runtime/") or normalized in GENERATED_BUILD_ARTIFACTS:
            # Hydrated/generated by the release pipeline at build time and
            # intentionally gitignored; they cannot exist in a clean checkout.
            continue
        assert (ROOT / relative).exists(), f"requiredPaths entry does not exist: {relative}"

    for item in manifest["datas"]:
        normalized = str(item["source"]).replace("\\", "/")
        if normalized.startswith("build/runtime/") or normalized in GENERATED_BUILD_ARTIFACTS:
            continue
        assert (ROOT / item["source"]).exists(), f"datas source does not exist: {item['source']}"

    # The prune policy/script must be release build inputs.
    required = {str(entry).replace("\\", "/") for entry in manifest["requiredPaths"]}
    assert "build/windows/prune_webview2_runtime.ps1" in required
    assert "build/windows/webview2-prune-policy.json" in required

    # Classification defaults must ship as data, not only as Python source.
    assert "builtin/categories.yaml" in required
    assert any(
        str(item.get("source")).replace("\\", "/") == "builtin"
        and str(item.get("target")).replace("\\", "/") == "builtin"
        for item in manifest["datas"]
    )


