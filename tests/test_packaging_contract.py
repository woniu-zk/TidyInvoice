def test_webview2_prune_policy_is_conservative_and_matches_runtime_manifest():
    policy = _load_prune_policy()
    keep = policy["keep"]
    prune = policy["prune"]

    required_files = set(keep["requiredFiles"])
    required_nested = set(keep["requiredNestedFiles"])
    required_dirs = set(keep["requiredDirectories"])
    locale_files = set(keep["localeFiles"])
    prune_entries = set(prune["topLevelEntries"]) | set(prune["nestedPaths"])

    # Startup-critical entries stay.
    assert {"msedgewebview2.exe", "msedge.dll", "resources.pak"} <= required_files
    assert "Locales" in required_dirs
    assert {"en-US.pak", "zh-CN.pak", "zh-TW.pak"} <= locale_files
    assert any("EmbeddedBrowserWebView.dll" in entry for entry in required_nested)

    # Pruned entries must never overlap the keep list.
    assert not prune_entries & required_files
    assert not prune_entries & required_nested
    assert not prune_entries & required_dirs
    assert not prune_entries & locale_files
    assert "Locales" not in prune_entries

    # The known-safe prune list documented in the release audit.
    assert {
        "WidevineCdm",
        "PdfPreview",
        "mspdf.dll",
        "mscopilot.exe",
        "learning_tools.dll",
        "oneauth.dll",
        "telclient.dll",
        "notification_helper.exe",
        "elevated_tracing_service.exe",
        "EBWebView/x86",
    } <= prune_entries

    expected = policy["expected"]
    assert 0 < int(expected["minBytesFreed"]) < int(expected["maxBytesFreed"])

    # runtime-sources.json must point at this policy and stay consistent with it.
    sources = json.loads(_read(RUNTIME_SOURCES_PATH))
    webview2 = sources["webview2"]
    assert webview2["prune_policy"] == "build/windows/webview2-prune-policy.json"
    runtime_required = set(webview2["required_files"])
    assert runtime_required <= required_files | required_dirs

    # Anything main.py validates at startup must survive pruning.
    main_source = _read(MAIN_PATH)
    validator_segment = main_source.split("def _validate_webview2_runtime_dir", 1)[1]
    validator_segment = validator_segment.split("def _configure_webview_runtime", 1)[0]
    validated_entries = set(re.findall(r'runtime_dir / "([^"]+)"', validator_segment))
    assert validated_entries
    assert validated_entries <= required_files | required_dirs


